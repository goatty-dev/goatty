//! Pairing: the code both screens show, the devices a host accepts and the
//! hosts a client pinned.
//!
//! Each side derives the code from both public keys, the host's pairing
//! nonce and the client's nonce. The host commits to its nonce before it
//! sees the client's and reveals it afterwards (`gateway`), so neither side
//! can choose its nonce to steer the code: a device in the middle, which
//! has to swap in its own keys, ends up with different codes on the two
//! screens (except with a chance of one in a million per attempt, and the
//! host allows ten attempts per pairing window).

use std::path::Path;

use anyhow::{Context, Result, bail};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use crate::{hex, identity, unhex};

/// Prefix for single-use headless pairing codes (`goatty-pair:...`).
pub const PAIR_TOKEN_PREFIX: &str = "goatty-pair:";
const PAIR_TOKEN_VERSION: u8 = 1;

/// A one-time pairing code generated by a host when its pairing window opens.
///
/// Carries the host's MagicDNS name, Tailscale IP, Serve port, ed25519 public
/// key (pinned immediately on the client), and a 128-bit single-use secret so
/// a headless host can be paired in one paste without a second confirmation
/// step on the host.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PairToken {
    pub version: u8,
    /// MagicDNS name without trailing dot (empty if MagicDNS is off).
    pub dns: String,
    /// Tailscale IP address when the token was created.
    pub addr: String,
    /// Friendly Tailscale host name.
    pub name: String,
    /// Serve TCP port on the host.
    pub port: u16,
    /// Host's ed25519 public key (64 hex chars).
    pub key: String,
    /// Single-use 128-bit pairing secret (32 hex chars).
    pub secret: String,
}

impl PairToken {
    /// Whether `s` starts with [`PAIR_TOKEN_PREFIX`].
    pub fn looks_like(s: &str) -> bool {
        s.trim().starts_with(PAIR_TOKEN_PREFIX)
    }

    /// Stable identifier for pinning this host in `hosts.json`: MagicDNS name,
    /// falling back to Tailscale IP or host name.
    pub fn host_id(&self) -> &str {
        if !self.dns.is_empty() {
            &self.dns
        } else if !self.addr.is_empty() {
            &self.addr
        } else {
            &self.name
        }
    }

    /// Display label for this host.
    pub fn display_name(&self) -> &str {
        if !self.name.is_empty() {
            &self.name
        } else if !self.dns.is_empty() {
            self.dns.split('.').next().unwrap_or(&self.dns)
        } else {
            &self.addr
        }
    }

    /// Encode as a compact single-line `goatty-pair:<base64url>` string.
    pub fn encode(&self) -> Result<String> {
        if self.version != PAIR_TOKEN_VERSION {
            bail!("unsupported pairing code version {}", self.version);
        }
        if self.port == 0 {
            bail!("pairing code has port 0");
        }
        if self.dns.is_empty() && self.addr.is_empty() {
            bail!("pairing code needs a host address or MagicDNS name");
        }
        let key = unhex::<32>(&self.key).context("invalid host key")?;
        let secret = unhex::<16>(&self.secret).context("invalid pairing secret")?;
        let mut buf = Vec::with_capacity(64 + self.dns.len() + self.addr.len() + self.name.len());
        buf.push(self.version);
        buf.extend_from_slice(&self.port.to_be_bytes());
        buf.extend_from_slice(&key);
        buf.extend_from_slice(&secret);
        for field in [&self.dns, &self.addr, &self.name] {
            let bytes = field.as_bytes();
            let len = u8::try_from(bytes.len()).map_err(|_| anyhow::anyhow!("pairing code field too long"))?;
            buf.push(len);
            buf.extend_from_slice(bytes);
        }
        Ok(format!("{PAIR_TOKEN_PREFIX}{}", b64url_encode(&buf)))
    }

    /// Decode a `goatty-pair:<base64url>` string. Whitespace inside the payload
    /// is ignored so tokens wrapped across terminal lines paste cleanly.
    pub fn decode(input: &str) -> Result<Self> {
        let trimmed = input.trim();
        let rest = trimmed.strip_prefix(PAIR_TOKEN_PREFIX).context("not a goatty pairing code (expected `goatty-pair:…`)")?;
        let compact: String = rest.chars().filter(|c| !c.is_ascii_whitespace()).collect();
        let buf = b64url_decode(&compact).context("corrupted pairing code")?;
        if buf.len() < 1 + 2 + 32 + 16 + 3 {
            bail!("pairing code is incomplete");
        }
        let version = buf[0];
        if version != PAIR_TOKEN_VERSION {
            bail!("unsupported pairing code version {version} (update goatty)");
        }
        let port = u16::from_be_bytes([buf[1], buf[2]]);
        if port == 0 {
            bail!("pairing code has port 0");
        }
        let key = hex(&buf[3..35]);
        if !identity::is_public_key(&key) {
            bail!("pairing code has an invalid host key");
        }
        let secret = hex(&buf[35..51]);
        let mut at = 51;
        let mut read_str = || -> Result<String> {
            let &len = buf.get(at).context("pairing code is truncated")?;
            at += 1;
            let end = at + usize::from(len);
            let slice = buf.get(at..end).context("pairing code is truncated")?;
            at = end;
            let s = std::str::from_utf8(slice).context("pairing code contains invalid UTF-8")?;
            Ok(s.chars().filter(|c| !c.is_control()).collect())
        };
        let dns = read_str()?.trim_end_matches('.').to_string();
        let addr = read_str()?;
        let name = read_str()?;
        if at != buf.len() {
            bail!("pairing code has unexpected trailing bytes");
        }
        if dns.is_empty() && addr.is_empty() {
            bail!("pairing code has no host address");
        }
        Ok(Self { version, dns, addr, name, port, key, secret })
    }
}

const B64URL: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";

fn b64url_encode(data: &[u8]) -> String {
    let mut out = String::with_capacity(data.len().div_ceil(3) * 4);
    for chunk in data.chunks(3) {
        let b0 = u32::from(chunk[0]);
        let b1 = chunk.get(1).copied().map_or(0, u32::from);
        let b2 = chunk.get(2).copied().map_or(0, u32::from);
        let triple = (b0 << 16) | (b1 << 8) | b2;
        out.push(B64URL[((triple >> 18) & 0x3f) as usize] as char);
        out.push(B64URL[((triple >> 12) & 0x3f) as usize] as char);
        if chunk.len() > 1 {
            out.push(B64URL[((triple >> 6) & 0x3f) as usize] as char);
        }
        if chunk.len() > 2 {
            out.push(B64URL[(triple & 0x3f) as usize] as char);
        }
    }
    out
}

fn b64url_val(b: u8) -> Option<u32> {
    match b {
        b'A'..=b'Z' => Some(u32::from(b - b'A')),
        b'a'..=b'z' => Some(u32::from(b - b'a') + 26),
        b'0'..=b'9' => Some(u32::from(b - b'0') + 52),
        b'-' => Some(62),
        b'_' => Some(63),
        _ => None,
    }
}

fn b64url_decode(s: &str) -> Result<Vec<u8>> {
    let s = s.trim_end_matches('=');
    let bytes = s.as_bytes();
    if bytes.len() % 4 == 1 {
        bail!("bad base64url length");
    }
    let mut out = Vec::with_capacity((bytes.len() * 3) / 4);
    for chunk in bytes.chunks(4) {
        let v0 = b64url_val(chunk[0]).context("bad base64url character")?;
        let v1 = b64url_val(chunk[1]).context("bad base64url character")?;
        let v2 = chunk.get(2).map(|&b| b64url_val(b).context("bad base64url character")).transpose()?;
        let v3 = chunk.get(3).map(|&b| b64url_val(b).context("bad base64url character")).transpose()?;
        out.push(((v0 << 2) | (v1 >> 4)) as u8);
        if let Some(v2) = v2 {
            out.push((((v1 & 0x0f) << 4) | (v2 >> 2)) as u8);
            if let Some(v3) = v3 {
                out.push((((v2 & 0x03) << 6) | v3) as u8);
            }
        }
    }
    Ok(out)
}

/// The 6-digit code for a pairing between `host_key` and `client_key`
/// (hex public keys) with their nonces.
pub fn code(host_key: &str, host_nonce: &str, client_key: &str, client_nonce: &str) -> String {
    let mut h = Sha256::new();
    for part in ["goatty-pair-code-v1", host_key, host_nonce, client_key, client_nonce] {
        h.update((part.len() as u32).to_le_bytes());
        h.update(part.as_bytes());
    }
    let d = h.finalize();
    let n = u64::from_le_bytes(d[..8].try_into().expect("8 bytes")) % 1_000_000;
    format!("{n:06}")
}

/// `123456` → `123 456`, as the screens show it.
pub fn spaced(code: &str) -> String {
    if code.len() == 6 { format!("{} {}", &code[..3], &code[3..]) } else { code.to_string() }
}

/// A device allowed to connect to this host.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Device {
    /// Its public key (hex).
    pub key: String,
    /// The name it gave when it paired (its hostname).
    pub name: String,
    pub paired_unix: u64,
}

/// The devices paired with this host (`devices.json`).
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct Devices {
    pub devices: Vec<Device>,
}

impl Devices {
    pub fn load(path: &Path) -> Result<Self> {
        crate::read_json(path)
    }

    pub fn save(&self, path: &Path) -> Result<()> {
        crate::write_atomic(path, &serde_json::to_vec_pretty(self)?, 0o600)
    }

    pub fn get(&self, key: &str) -> Option<&Device> {
        self.devices.iter().find(|d| d.key == key)
    }

    /// Add or rename a device.
    pub fn add(&mut self, device: Device) {
        self.devices.retain(|d| d.key != device.key);
        self.devices.push(device);
    }

    /// Remove the devices whose key starts with `prefix` (at least 8 hex
    /// digits, so a typo can't revoke everything). Returns the removed ones.
    pub fn revoke(&mut self, prefix: &str) -> Vec<Device> {
        if prefix.len() < 8 {
            return Vec::new();
        }
        let (gone, kept) = std::mem::take(&mut self.devices).into_iter().partition(|d| d.key.starts_with(prefix));
        self.devices = kept;
        gone
    }
}

/// A host this computer paired with.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct KnownHost {
    /// Its MagicDNS name without the trailing dot (`box.tail1234.ts.net`):
    /// what the host list keys it by.
    pub dns: String,
    /// Its Tailscale host name, as shown.
    pub name: String,
    /// Its tailnet address when it paired (used when the status can't be read).
    pub addr: String,
    pub port: u16,
    /// Its public key (hex): a host that shows another is refused.
    pub key: String,
    pub paired_unix: u64,
}

/// The hosts this computer paired with (`hosts.json`).
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct KnownHosts {
    pub hosts: Vec<KnownHost>,
}

impl KnownHosts {
    pub fn load(path: &Path) -> Result<Self> {
        crate::read_json(path)
    }

    pub fn save(&self, path: &Path) -> Result<()> {
        crate::write_atomic(path, &serde_json::to_vec_pretty(self)?, 0o600)
    }

    pub fn get(&self, dns: &str) -> Option<&KnownHost> {
        self.hosts.iter().find(|h| h.dns == dns)
    }

    /// Find a paired host by MagicDNS name (with or without trailing dot),
    /// friendly name (case-insensitive), or Tailscale IP address.
    pub fn find(&self, query: &str) -> Option<&KnownHost> {
        let q = query.trim().trim_end_matches('.');
        if q.is_empty() {
            return None;
        }
        self.hosts
            .iter()
            .find(|h| h.dns.eq_ignore_ascii_case(q))
            .or_else(|| self.hosts.iter().find(|h| h.name.eq_ignore_ascii_case(q)))
            .or_else(|| self.hosts.iter().find(|h| !h.addr.is_empty() && h.addr.eq_ignore_ascii_case(q)))
    }

    pub fn add(&mut self, host: KnownHost) {
        self.hosts.retain(|h| h.dns != host.dns);
        self.hosts.push(host);
    }

    pub fn remove(&mut self, dns: &str) -> bool {
        let before = self.hosts.len();
        self.hosts.retain(|h| h.dns != dns);
        self.hosts.len() != before
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn code_depends_on_every_input() {
        let c = code("aa", "11", "bb", "22");
        assert_eq!(c.len(), 6);
        assert!(c.chars().all(|c| c.is_ascii_digit()));
        assert_eq!(c, code("aa", "11", "bb", "22"));
        for other in
            [code("ab", "11", "bb", "22"), code("aa", "12", "bb", "22"), code("aa", "11", "bc", "22"), code("aa", "11", "bb", "23")]
        {
            assert_ne!(c, other);
        }
        // Field boundaries count: moving a character between fields changes it.
        assert_ne!(code("aab", "11", "b", "22"), code("aa", "11", "bb", "22"));
        assert_eq!(spaced("012345"), "012 345");
    }

    #[test]
    fn devices_and_hosts_persist() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("devices.json");
        let mut d = Devices::load(&path).unwrap();
        assert!(d.devices.is_empty());
        d.add(Device { key: "a".repeat(64), name: "laptop".into(), paired_unix: 1 });
        d.add(Device { key: "b".repeat(64), name: "desk".into(), paired_unix: 2 });
        d.add(Device { key: "a".repeat(64), name: "laptop2".into(), paired_unix: 3 });
        d.save(&path).unwrap();
        let mut d = Devices::load(&path).unwrap();
        assert_eq!(d.devices.len(), 2);
        assert_eq!(d.get(&"a".repeat(64)).unwrap().name, "laptop2");
        assert!(d.revoke("aaa").is_empty(), "too short a prefix revokes nothing");
        assert_eq!(d.revoke("aaaaaaaa").len(), 1);
        assert!(d.get(&"a".repeat(64)).is_none());

        let path = dir.path().join("hosts.json");
        let mut h = KnownHosts::load(&path).unwrap();
        h.add(KnownHost {
            dns: "box.ts.net".into(),
            name: "box".into(),
            addr: "100.1.2.3".into(),
            port: 7422,
            key: "c".repeat(64),
            paired_unix: 1,
        });
        h.save(&path).unwrap();
        let mut h = KnownHosts::load(&path).unwrap();
        assert_eq!(h.get("box.ts.net").unwrap().addr, "100.1.2.3");
        assert_eq!(h.find("BOX.TS.NET.").unwrap().name, "box");
        assert_eq!(h.find("BOX").unwrap().dns, "box.ts.net");
        assert_eq!(h.find("100.1.2.3").unwrap().dns, "box.ts.net");
        assert!(h.find("nope").is_none());
        assert!(h.remove("box.ts.net"));
        assert!(!h.remove("box.ts.net"));
    }

    #[test]
    fn pair_token_round_trips_and_tolerates_line_wraps() {
        let tok = PairToken {
            version: 1,
            dns: "vps.tail1234.ts.net".into(),
            addr: "100.64.0.9".into(),
            name: "vps".into(),
            port: 7500,
            key: "ab".repeat(32),
            secret: "cd".repeat(16),
        };
        let encoded = tok.encode().unwrap();
        assert!(PairToken::looks_like(&encoded), "{encoded}");
        assert!(!encoded.contains(char::is_whitespace), "{encoded}");
        assert_eq!(PairToken::decode(&encoded).unwrap(), tok);
        // Terminal line wraps inside the payload are tolerated.
        let wrapped = format!("  {}\n  {}  ", &encoded[..40], &encoded[40..]);
        assert_eq!(PairToken::decode(&wrapped).unwrap(), tok);
        // Without MagicDNS, host_id falls back to IP.
        let no_dns = PairToken { dns: String::new(), ..tok.clone() };
        assert_eq!(no_dns.host_id(), "100.64.0.9");
        assert_eq!(PairToken::decode(&no_dns.encode().unwrap()).unwrap(), no_dns);
        // Bad inputs are rejected.
        assert!(PairToken::decode("not-a-token").is_err());
        assert!(PairToken::decode("goatty-pair:!!!").is_err());
        assert!(PairToken::decode("goatty-pair:AA").is_err());
    }
}
